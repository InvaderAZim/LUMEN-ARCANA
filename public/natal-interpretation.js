const finite=x=>typeof x==='number'&&Number.isFinite(x);
const norm=x=>((x%360)+360)%360;
const signOf=x=>SIGNS[Math.floor(norm(x)/30)];
export function natalHouseAt(angle,cusps){
 if(!finite(angle)||!Array.isArray(cusps)||cusps.length!==12||!cusps.every(finite))return null;
 for(let i=0;i<12;i++){
  const start=norm(cusps[i]),span=norm(cusps[(i+1)%12]-start),distance=norm(angle-start);
  if(span>0&&distance<span)return i+1;
 }
 return null;
}
