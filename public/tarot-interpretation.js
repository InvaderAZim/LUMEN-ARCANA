const word = value => String(value == null ? '' : value).trim();
const cardTheme = card => {
  const name=word(card?.name);
  if(MAJOR.has(name)){
    const m=MAJOR.get(name);
    return {meaning:m[0],shadow:m[1],action:m[2]};
  }
  for(const [suit,theme] of Object.entries(SUITS)){
    if(name.endsWith(' '+suit)){
      const rank=name.slice(0,-(suit.length+1)),r=RANKS[rank];
      if(r)return {meaning:r[0]+' у сфері, що символізує '+theme[0],shadow:r[1]+'; також можливі '+theme[1],action:theme[2]};
    }
  }
  const keywords=Array.isArray(card?.keywords)?card.keywords.slice(0,3).map(word).filter(Boolean):[];
  return {meaning:keywords.length?'теми '+keywords.join(', '):'пошук особистого сенсу',shadow:'поспішні висновки без перевірки обставин',action:'запиши свою асоціацію з образом і перевір її на практиці'};
};

export function interpretTarotCard(card,{question='',language='uk'}={}){
  const name=word(card?.name)||'Карта';
  const position=word(card?.position)||'Головний фокус';
  const reversed=card?.orientation==='reversed';
  const theme=cardTheme(card);
  if(language!=='uk'){
    const keywords=Array.isArray(card?.keywords)?card.keywords.map(word).filter(Boolean).join(', '):'reflection';
    return {card:name,position,observation:'The card appears '+(reversed?'reversed':'upright')+'.',
      symbolism:'Symbolic themes: '+keywords+'. '+(reversed?'Consider what may be blocked or overemphasized.':'Consider what these themes mean in your situation.'),
      positionMeaning:'In the position "'+position+'", consider which part of the question deserves attention.',
      context:question?'Use the question "'+word(question)+'" as a prompt for reflection, not as evidence of an outcome.':'Use the image as a prompt for reflection.',
      practice:'Write down one action under your control and one assumption to verify.'};
  }
  const hint=POSITION_HINTS.find(([pattern])=>pattern.test(position))?.[1]||'визнач, як цей образ пов’язаний саме з цією частиною запиту';
  return {
    card:name,position,
    observation:'Карта «'+name+'» у позиції «'+position+'» — '+(reversed?'перевернута.':'пряма.'),
    symbolism:'У символічному читанні карта означає '+theme.meaning+'. '+(reversed?'Перевернуте положення пропонує звернути увагу на '+theme.shadow+'.':'Це тема для осмислення, а не підтвердження майбутньої події.'),
    positionMeaning:'У позиції «'+position+'» '+hint+'.',
    context:question?'У контексті запиту «'+word(question)+'» зістав це значення з фактами й власним досвідом, не приписуючи карті знання прихованих подій.':'Зістав образ зі своїми реальними обставинами.',
    practice:'Практичний крок: '+theme.action+'.'
  };
}

export function synthesizeTarotSpread(cards,{question='',language='uk'}={}){
  const list=Array.isArray(cards)?cards:[];
  if(!list.length)return language==='uk'?'Для висновку потрібна хоча б одна карта.':'At least one card is needed for a reading.';
  const first=list[0],last=list[list.length-1];
  if(language!=='uk')return 'Read the sequence from "'+word(first?.position)+'" to "'+word(last?.position)+'". Compare the card themes with actual evidence and choose one practical next step. Tarot does not establish facts or predict outcomes.';
  const prefix=question?'Щодо питання «'+word(question)+'» ':'У цьому розкладі ';
  if(list.length===1)return prefix+'основний образ — «'+word(first.name)+'» у позиції «'+word(first.position)+'». Його тема — '+cardTheme(first).meaning+'. Сприймай це як спосіб уточнити власні пріоритети, а не як гарантію події.';
  const middle=list.slice(1,-1).map(c=>'«'+word(c.name)+'» («'+word(c.position)+'»)').join(', ');
  return prefix+'послідовність починається з «'+word(first.name)+'» («'+word(first.position)+'»), '+(middle?'розвивається через '+middle+' і ':'')+'завершується «'+word(last.name)+'» («'+word(last.position)+'»). Початкова тема — '+cardTheme(first).meaning+'; підсумкова — '+cardTheme(last).meaning+'. Перевір, які частини цього образу підтверджуються фактами, і визнач один реалістичний крок.';
}
